#!/usr/bin/env python3
"""Prepare pixel-exact art templates and inspect human/AI outpainting candidates.

No images are generated by this script. It only preserves the approved paintings,
packages the masked drawing area, and refuses distorted or incompatible images.
Every accepted candidate still needs manual visual review before promotion.

  python3 scripts/laria_d2_outpaint.py templates --output /tmp/d2-templates
  python3 scripts/laria_d2_outpaint.py inspect --subject math --input output.png --output /tmp/d2-candidates
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
from PIL import Image, ImageChops, ImageStat

ROOT = Path(__file__).resolve().parents[1] / "laer-litt-mer"
SUBJECTS = {
    "norwegian": "bokskogen",
    "math": "tallenga",
    "english": "ordlandsbyen",
    "geography": "nordlysleiren",
}
SIZE = (941, 1672)
CONTEXT = 300
PAINTED = 425
OVERLAP = 43

class ArtError(ValueError):
    pass

def original_image(root: Path, subject: str) -> Image.Image:
    name = SUBJECTS[subject]
    source = root / "locked-journeys" / f"{name}-locked-20261010.png"
    if not source.is_file():
        raise ArtError(f"Locked original missing: {source}")
    with Image.open(source) as im:
        if im.size != SIZE:
            raise ArtError(f"Original dimensions changed for {name}: {im.size}")
        return im.convert("RGB")

def generate_templates(root: Path, output: Path) -> None:
    output.mkdir(parents=True, exist_ok=True)
    for subject, name in SUBJECTS.items():
        original = original_image(root, subject)
        context = original.crop((0, SIZE[1] - CONTEXT, SIZE[0], SIZE[1]))
        art = Image.new("RGBA", (SIZE[0], CONTEXT + PAINTED), (0, 0, 0, 0))
        art.paste(context, (0, 0))
        art.save(output / f"{name}-outpaint-exact.png")
        mask = Image.new("L", art.size, 255)
        mask.paste(0, (0, 0, SIZE[0], CONTEXT))
        mask.save(output / f"{name}-paint-mask-white.png")
        anchor = Image.new("RGBA", (SIZE[0], OVERLAP + PAINTED), (0, 0, 0, 0))
        anchor.paste(original.crop((0, SIZE[1] - OVERLAP, SIZE[0], SIZE[1])), (0, 0))
        anchor.save(output / f"{name}-43px-exact-anchor.png")
    (output / "README.txt").write_text(
        "LARIA D2 PIXEL-EXACT OUTPAINT TEMPLATES\n\n"
        "Originals are unchanged 941x1672 PNGs. The first 300 rows of each\n"
        "941x725 context are EXACT original pixels. Paint ONLY the empty\n"
        "425 rows; mask white=paint, black=preserve. Supply a 941x725\n"
        "opaque PNG image for inspection. Never generate phone UI, stars,\n"
        "badges, chests, signposts or the fox in the extra terrain.\n"
        "The independent 43px anchors are for seam checking, NOT artwork.\n",
        encoding="utf-8",
    )

def inspect_candidate(root: Path, subject: str, input_image: Path, output: Path,
                      maximum_seam: float = 32.0) -> dict:
    original = original_image(root, subject)
    name = SUBJECTS[subject]
    with Image.open(input_image) as handle:
        if handle.size != (SIZE[0], CONTEXT + PAINTED):
            raise ArtError(f"Expected 941x725 opaque painting; got {handle.size}")
        candidate = handle.convert("RGBA")
    if candidate.getextrema()[3][0] < 255:
        raise ArtError("Image still has transparent unpainted areas")
    candidate = candidate.convert("RGB")
    supplied_context = candidate.crop((0, 0, SIZE[0], CONTEXT))
    exact_context = original.crop((0, SIZE[1] - CONTEXT, SIZE[0], SIZE[1]))
    delta = ImageChops.difference(supplied_context, exact_context)
    context_mae = sum(ImageStat.Stat(delta).mean) / 3
    if context_mae > 1.25:
        raise ArtError(f"Source art was repainted (context MAE={context_mae:.2f}); "
                       "use masked editing preserving all first 300 rows")
    new_paint = candidate.crop((0, CONTEXT, SIZE[0], CONTEXT + PAINTED))
    last = original.crop((0, SIZE[1] - 1, SIZE[0], SIZE[1]))
    first = new_paint.crop((0, 0, SIZE[0], 1))
    seam = sum(ImageStat.Stat(ImageChops.difference(last, first)).mean) / 3
    if seam > maximum_seam:
        raise ArtError(f"Visible horizontal seam probable (channel MAE={seam:.1f} > {maximum_seam:.1f}); "
                       "redo painting from the exact original edge")
    pixels = new_paint.load()
    sample_count = bright_count = 0
    for y in range(0, PAINTED, 4):
        for x in range(0, SIZE[0], 4):
            r, g, b = pixels[x, y]
            bright_count += r > 222 and g > 210 and b > 178
            sample_count += 1
    light_ratio = bright_count / sample_count
    if light_ratio > 0.16:
        raise ArtError(f"Suspicious cream/white panel in painted terrain ({light_ratio:.0%} very bright)")
    output.mkdir(parents=True, exist_ok=True)
    result = Image.new("RGB", (SIZE[0], OVERLAP + PAINTED))
    result.paste(original.crop((0, SIZE[1] - OVERLAP, SIZE[0], SIZE[1])), (0, 0))
    result.paste(new_paint, (0, OVERLAP))
    webp = output / f"{name}-ground-CANDIDATE.webp"
    result.save(webp, "WEBP", lossless=True, method=6)
    with Image.open(webp) as check:
        restored = check.convert("RGB").crop((0, 0, SIZE[0], OVERLAP))
    exact = original.crop((0, SIZE[1] - OVERLAP, SIZE[0], SIZE[1]))
    if ImageChops.difference(restored, exact).getbbox() is not None:
        webp.unlink(missing_ok=True)
        raise ArtError("Lossless output failed original-pixel identity check")
    preview = Image.new("RGB", (SIZE[0], 300 + PAINTED))
    preview.paste(original.crop((0, SIZE[1]-300, SIZE[0], SIZE[1])), (0, 0))
    preview.paste(new_paint, (0, 300))
    preview.save(output / f"{name}-seam-review.png", optimize=True)
    report = {"subject": subject, "candidate": webp.name,
              "originalPreserved": True, "first43PixelRowsExact": True,
              "contextMAE": round(context_mae, 3), "seamMAE": round(seam, 3),
              "lightRatio": round(light_ratio, 4), "visualApproval": False}
    (output / f"{name}-qa-report.json").write_text(json.dumps(report,indent=2), encoding="utf-8")
    return report

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=["templates", "inspect"])
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--subject", choices=sorted(SUBJECTS))
    parser.add_argument("--input", type=Path)
    args = parser.parse_args()
    if args.mode == "templates":
        generate_templates(args.root, args.output)
        print("Created exact-source outpainting templates for all four worlds in", args.output)
    else:
        if not args.subject or not args.input:
            parser.error("inspect needs --subject and --input")
        print(json.dumps(inspect_candidate(args.root,args.subject,args.input,args.output),indent=2))

if __name__ == "__main__":
    main()
